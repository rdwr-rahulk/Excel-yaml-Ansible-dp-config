"""Cross-row and cross-sheet validation of normalized workbook data."""

from __future__ import annotations

import ipaddress
from collections import Counter, defaultdict
from dataclasses import dataclass, field
from typing import Dict, List, Optional, Set, Tuple

from . import schema as S
from .normalize import NormalizedData, NRow
from .report import Report


@dataclass
class Options:
    allow_ipv6: bool = False
    devices: Optional[List[str]] = None    # restrict to these device names (must also be included)


@dataclass
class ValidationContext:
    included: List[Tuple[str, str]] = field(default_factory=list)   # (name, ip)
    external: Dict[str, Set[Tuple[str, str]]] = field(default_factory=dict)  # device -> {(type, name)}


def _rows(data: NormalizedData, sheet: str, device: str) -> List[NRow]:
    return [r for r in data.sheets.get(sheet, []) if r.device == device]


def validate(data: NormalizedData, report: Report, options: Optional[Options] = None) -> ValidationContext:
    options = options or Options()
    ctx = ValidationContext()
    rc = data.run_control

    # ---------------- Devices ----------------
    names = Counter(r.get("name") for r in data.devices if r.get("name"))
    ips = Counter(r.get("ip") for r in data.devices if r.get("ip"))
    for r in data.devices:
        if names.get(r.get("name"), 0) > 1:
            report.error("DUPLICATE_DEVICE", f"device '{r.get('name')}' appears more than once", sheet="Devices",
                         cell=r.cell("name"), safety=True)
        if ips.get(r.get("ip"), 0) > 1:
            report.error("DUPLICATE_DEVICE_IP", f"IP {r.get('ip')} appears more than once", sheet="Devices",
                         cell=r.cell("ip"), safety=True)
    known_devices = {r.get("name") for r in data.devices if r.get("name")}
    included = [(r.get("name"), r.get("ip")) for r in data.devices if r.ok and r.get("include")]
    if options.devices:
        unknown = set(options.devices) - {n for n, _ in included}
        for n in sorted(unknown):
            report.error("DEVICE_NOT_INCLUDED", f"--device {n} is not a device with 'Include in this run?' = Yes",
                         sheet="Devices", safety=True)
        included = [(n, ip) for n, ip in included if n in options.devices]
    if not included:
        report.error("NO_DEVICES", "no device is selected (set 'Include in this run?' = Yes)", sheet="Devices", safety=True)
    ctx.included = included
    included_names = {n for n, _ in included}

    # rows referring to unknown devices
    for sheet, rows in data.sheets.items():
        for r in rows:
            if r.device and r.device not in known_devices:
                report.error("UNKNOWN_DEVICE", f"device '{r.device}' is not on the Devices sheet", sheet=sheet,
                             cell=f"A{r.row}", safety=True)

    # ---------------- Run_Control ----------------
    for t in S.UNSUPPORTED_TOGGLES:
        if rc.get(t) is True:
            report.error("UNSUPPORTED_SECTION", f"'{S.rc_label(t)}' must be No - this section is not generated by the POC converter",
                         sheet="Run_Control", cell=data.run_control_cells.get(t), field=t, safety=True)
    needs_ticket = rc.get(S.AUTHORIZE_APPLY) is True or rc.get("environment") == "production"
    if needs_ticket:
        for k in ("change_ticket", "authorized_by"):
            if not rc.get(k):
                report.error("AUTHORIZATION_MISSING", f"'{S.rc_label(k)}' is required when "
                             f"{S.rc_label(S.AUTHORIZE_APPLY)} = Yes or Environment = production",
                             sheet="Run_Control", cell=data.run_control_cells.get(k),
                             field=k, safety=True)

    # ---------------- per device ----------------
    for dev, _ip in included:
        _validate_device(dev, data, report, options, ctx)

    # rows for devices that exist but are not included
    skipped = Counter(r.device for rows in data.sheets.values() for r in rows
                      if r.device in known_devices and r.device not in included_names)
    for dev, n in sorted(skipped.items()):
        report.info("DEVICE_SKIPPED", f"{n} row(s) for device '{dev}' skipped (not included in this run)", device=dev)

    for sheet, n in sorted(data.reference_rows.items()):
        if n:
            report.warning("REFERENCE_SHEET_NOT_CONVERTED", f"{n} row(s) on reference-only sheet '{sheet}' are not converted",
                           sheet=sheet)

    for (dev, sheet, header), n in sorted(data.defaults.items(), key=lambda x: tuple(str(p) for p in x[0])):
        if dev not in included_names:
            continue
        if header.startswith("INFO:"):
            report.warning("INFO_COLUMN_NOT_CONVERTED", f"{n} value(s) in '{header[5:]}' are not converted "
                           "(no module parameter consumes this column)", sheet=sheet, device=dev)
        elif sheet == "Policies":
            report.info("NOT_BOUND", f"{n} polic(ies) leave '{header}' blank - no profile of that type is bound",
                        sheet=sheet, device=dev)
        else:
            report.default("LEFT_TO_DEFAULT", f"{n} row(s) leave '{header}' blank - key omitted, module/device default applies",
                           sheet=sheet, device=dev)
    return ctx


def _dupes(rows: List[NRow], keyfn, sheet: str, what: str, report: Report, dev: str, code="DUPLICATE_KEY"):
    seen: Dict[tuple, NRow] = {}
    for r in rows:
        k = keyfn(r)
        if None in k:
            continue
        if k in seen:
            report.error(code, f"duplicate {what} {k} (first on row {seen[k].row})", sheet=sheet, cell=f"A{r.row}", device=dev)
        else:
            seen[k] = r


def _validate_device(dev: str, data: NormalizedData, report: Report, options: Options, ctx: ValidationContext):
    rc = data.run_control
    on = {t: rc.get(t) is True for t in S.RUN_CONTROL_TOGGLES}

    # ---- External_References ----
    ext_rows = _rows(data, "External_References", dev)
    _dupes(ext_rows, lambda r: (r.get("type"), r.get("name")), "External_References", "external reference", report, dev)
    external = {(r.get("type"), r.get("name")) for r in ext_rows if r.ok}
    ctx.external[dev] = external

    # ---- Network_Classes ----
    nc = _rows(data, "Network_Classes", dev)
    _dupes(nc, lambda r: (r.get("name"), r.get("group_index")), "Network_Classes", "(class, group index)", report, dev)
    _dupes(nc, lambda r: (r.get("name"), r.get("address"), r.get("mask")), "Network_Classes", "(class, address, mask)", report, dev)
    by_class: Dict[str, List[NRow]] = defaultdict(list)
    for r in nc:
        if r.get("name") is not None:
            by_class[r.get("name")].append(r)
        addr, mask = r.get("address"), r.get("mask")
        if addr is None or mask is None:
            continue
        ip = ipaddress.ip_address(addr)
        if ip.version == 6:
            if not options.allow_ipv6:
                report.error("IPV6_UNCONFIRMED", f"IPv6 address {addr}: IPv6 support in create_network_class.py is not "
                             "confirmed (use --allow-ipv6 after confirming)", sheet="Network_Classes", cell=r.cell("address"),
                             device=dev, safety=True)
            if not mask.isdigit() or not 0 <= int(mask) <= 128:
                report.error("BAD_MASK", f"IPv6 mask must be a prefix length 0-128, got '{mask}'", sheet="Network_Classes",
                             cell=r.cell("mask"), device=dev)
        elif mask.isdigit() and not 0 <= int(mask) <= 32:
            report.error("BAD_MASK", f"IPv4 prefix length must be 0-32, got {mask}", sheet="Network_Classes",
                         cell=r.cell("mask"), device=dev)
    for cls, rows in by_class.items():
        idx = sorted(r.get("group_index") for r in rows if r.get("group_index") is not None)
        if idx and idx != list(range(len(idx))):
            report.error("GROUP_INDEX_GAP", f"Group Index for class '{cls}' must be 0..{len(idx) - 1} without gaps or "
                         f"duplicates, found {idx}", sheet="Network_Classes", cell=f"C{rows[0].row}", device=dev, safety=True)

    # ---- CL ----
    clp = _rows(data, "CL_Protections", dev)
    _dupes(clp, lambda r: (r.get("name"),), "CL_Protections", "protection name", report, dev)
    clm = _rows(data, "CL_Profile_Members", dev)
    _dupes(clm, lambda r: (r.get("name"), r.get("protection")), "CL_Profile_Members", "(profile, protection)", report, dev)

    # ---- TF ----
    tfp = _rows(data, "TF_Profiles", dev)
    _dupes(tfp, lambda r: (r.get("profile_name"),), "TF_Profiles", "profile name", report, dev)
    tfr = _rows(data, "TF_Rules", dev)
    _dupes(tfr, lambda r: (r.get("profile_name"), r.get("protection_name")), "TF_Rules", "(profile, rule)", report, dev)
    for r in tfr:
        proto = r.get("protocol")
        if proto in ("tcp", "any") and "tcp_flags" not in r.values and r.ok:
            report.error("BLANK_EXPLICIT", "'TCP Flags' must be chosen when Protocol is TCP or Any - blank flags default to "
                         "enable in create_traffic_filter.py", sheet="TF_Rules", cell=r.cell("tcp_flags"), device=dev, safety=True)
            r.ok = False
        if proto not in (None, "tcp", "any") and "tcp_flags" in r.values:
            report.error("TCP_FLAGS_NOT_APPLICABLE", f"TCP Flags must be blank for protocol '{proto}'", sheet="TF_Rules",
                         cell=r.cell("tcp_flags"), device=dev)
            r.ok = False
        unit = r.get("threshold_unit")
        need = {"pps": "threshold_pps", "kbps": "threshold_kbps"}.get(unit)
        if need and need not in r.values:
            report.error("BLANK_EXPLICIT", f"'{need}' is required when Threshold Unit = {unit}", sheet="TF_Rules",
                         cell=r.cell(need), device=dev, safety=True)
            r.ok = False

    # ---- OOS / BDoS ----
    _dupes(_rows(data, "OOS_Profiles", dev), lambda r: (r.get("name"),), "OOS_Profiles", "profile name", report, dev)
    bd = _rows(data, "BDoS_Profiles", dev)
    _dupes(bd, lambda r: (r.get("name"),), "BDoS_Profiles", "profile name", report, dev)
    for r in bd:
        if r.get("bdos_rate_limit") == "user_defined":
            for k in ("user_defined_rate_limit", "user_defined_rate_limit_unit"):
                if k not in r.values:
                    report.error("BLANK_REQUIRED", f"'{k}' is required when BDoS Rate Limit = User Defined",
                                 sheet="BDoS_Profiles", cell=r.cell(k), device=dev)
                    r.ok = False

    # ---- Policies ----
    pol = _rows(data, "Policies", dev)
    _dupes(pol, lambda r: (r.get("policy_name"),), "Policies", "policy name", report, dev)
    prio = Counter(r.get("priority") for r in pol if r.get("priority"))
    for p, n in prio.items():
        if n > 1:
            report.warning("DUPLICATE_PRIORITY", f"priority {p} is used by {n} policies", sheet="Policies", device=dev)

    # ---- references ----
    internal_on: Dict[str, Set[str]] = {}
    internal_off: Dict[str, Set[str]] = {}
    for rtype, (sheet, key, toggle) in S.INTERNAL_REF_SOURCES.items():
        names = {r.get(key) for r in _rows(data, sheet, dev) if r.get(key)}
        (internal_on if on.get(toggle) else internal_off)[rtype] = names
    used_external: Set[Tuple[str, str]] = set()

    def resolve(rtype: str, name: str, sheet: str, cell: str):
        if rtype == "Network Class" and name == "any":
            return
        in_wb = name in internal_on.get(rtype, set())
        declared = (rtype, name) in external
        if in_wb and declared:
            report.error("EXT_CONFLICT", f"{rtype} '{name}' is both created by this workbook and declared external",
                         sheet=sheet, cell=cell, device=dev, safety=True)
        elif in_wb:
            return
        elif declared:
            used_external.add((rtype, name))
        elif name in internal_off.get(rtype, set()):
            toggle = next(t for rt, (_, _, t) in S.INTERNAL_REF_SOURCES.items() if rt == rtype)
            report.error("REF_TOGGLE_OFF", f"{rtype} '{name}' is defined in the workbook but "
                         f"Run_Control '{S.rc_label(toggle)}' = No; declare it "
                         "on External_References if it already exists on the device", sheet=sheet, cell=cell, device=dev,
                         safety=True)
        else:
            report.error("UNRESOLVED_REF", f"{rtype} '{name}' is neither defined in this workbook nor declared on "
                         "External_References", sheet=sheet, cell=cell, device=dev, safety=True)

    ref_fields = [f for f in S.POLICIES.fields if f.kind == "ref"]
    for r in pol:
        for f in ref_fields:
            if f.key in r.values:
                resolve(f.ref, r.values[f.key], "Policies", r.cell(f.key))
    for r in clm:
        if "protection" in r.values:
            resolve("Connection Limit Protection", r.values["protection"], "CL_Profile_Members", r.cell("protection"))
    for r in tfr:
        if "profile_name" in r.values:
            resolve("Traffic Filter Profile", r.values["profile_name"], "TF_Rules", r.cell("profile_name"))

    for rtype, name in sorted(used_external):
        report.unverified("EXTERNAL_REF", f"{rtype} '{name}' (declared, not checked against the device)", device=dev)
    for rtype, name in sorted(external - used_external):
        report.info("EXTERNAL_UNUSED", f"{rtype} '{name}' is declared but not referenced", device=dev)

    # ---- toggle vs content ----
    for spec in (S.NETWORK_CLASSES, S.CL_PROTECTIONS, S.TF_PROFILES, S.OOS_PROFILES, S.BDOS_PROFILES, S.POLICIES):
        n = len(_rows(data, spec.name, dev))
        if on.get(spec.toggle) and n == 0:
            report.warning("TOGGLE_ON_EMPTY", f"Run_Control '{S.rc_label(spec.toggle)}' = Yes but '{spec.name}' has no "
                           "rows for this device", sheet=spec.name, device=dev)
        if not on.get(spec.toggle) and n:
            report.warning("TOGGLE_OFF_ROWS", f"Run_Control '{S.rc_label(spec.toggle)}' = No: {n} row(s) on "
                           f"'{spec.name}' are not converted", sheet=spec.name, device=dev)
