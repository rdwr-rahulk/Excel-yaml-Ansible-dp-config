"""Post-Phase-A read-back of network classes via playbooks/get_network_class.yml.

Network classes are the section where a partial failure is reported only as a
warning, so they are read back and compared group by group before Phase B is
allowed. Other sections are reported as "read-back not implemented in the POC".
"""

from __future__ import annotations

import ipaddress
from typing import Dict, List, Set, Tuple

from .report import Report
from .runner import PlaybookRun
from .yamlio import dump

NOT_IMPLEMENTED = ("cl_protections", "oos_profiles", "bdos_profiles", "create_tf_profiles", "create_security_policies")


def get_vars_text(ip: str, class_names: List[str]) -> str:
    return dump({"dp_ip": [ip], "filter_class_names": list(class_names)},
                ["Generated by xl2yaml for the Phase A read-back (read-only)."])


def _prefix(address: str, mask) -> int:
    m = str(mask)
    if m.isdigit():
        return int(m)
    return ipaddress.ip_network(f"{address}/{m}", strict=False).prefixlen


def intended_groups(cfg: Dict) -> Set[Tuple[str, int, str, int]]:
    out = set()
    for nc in cfg.get("netclasses") or []:
        for i, g in enumerate(nc.get("groups") or []):
            out.add((nc["name"], i, g["address"], _prefix(g["address"], g["mask"])))
    return out


def compare_network_classes(run: PlaybookRun, cfg: Dict, report: Report, device: str) -> bool:
    before = len(report.errors)
    ip = cfg["dp_ip"][0]
    items = [i for i in run.items("get_network_class") if i.get("item") == ip and i["status"] in ("ok", "changed")]
    if run.returncode != 0 or not items:
        report.error("READBACK_FAILED", "could not read network classes back from the device", device=device, safety=True)
        return False
    table = (items[0]["result"].get("response") or {}).get("rsBWMNetworkTable") or []
    want = intended_groups(cfg)
    classes = {w[0] for w in want}
    got = set()
    for e in table:
        name = e.get("rsBWMNetworkName")
        if name not in classes:
            continue
        try:
            got.add((name, int(e.get("rsBWMNetworkSubIndex")), e.get("rsBWMNetworkAddress"),
                     _prefix(e.get("rsBWMNetworkAddress"), e.get("rsBWMNetworkMask"))))
        except (TypeError, ValueError):
            report.error("READBACK_UNPARSABLE", f"unexpected entry from device: {e}", device=device, safety=True)
    for g in sorted(want - got):
        report.error("READBACK_MISSING", f"network class {g[0]}[{g[1]}] {g[2]}/{g[3]} not found on the device",
                     device=device, safety=True)
    for g in sorted(got - want):
        report.error("READBACK_UNEXPECTED", f"network class {g[0]}[{g[1]}] {g[2]}/{g[3]} exists on the device but was "
                     "not intended", device=device, safety=True)
    for section in NOT_IMPLEMENTED:
        if cfg.get(section):
            report.info("READBACK_NOT_IMPLEMENTED", f"read-back of '{section}' is not implemented in the POC - verify "
                        "with the get_* playbooks", device=device)
    passed = len(report.errors) == before
    if passed:
        report.info("READBACK_PASS", f"{len(want)} network group(s) verified on the device", device=device)
    return passed
