"""Build one create_vars.yml structure per included device.

Key order follows vars/create_vars.yml.example so diffs against hand-written
files stay readable. Every section create_full_config.yml reads is written,
even when empty, so nothing is ever looked up from an older file.
"""

from __future__ import annotations

from typing import Dict, List

from . import schema as S
from .normalize import NormalizedData, NRow
from .validator import ValidationContext

CL_ORDER = ("name", "protection_type", "protocol", "threshold", "app_port_group", "tracking_type", "action",
            "packet_report", "index")
TF_RULE_ORDER = ("profile_name", "protection_name", "status", "match_criteria", "protocol", "threshold_pps",
                 "threshold_kbps", "threshold_unit", "tcp_syn", "tcp_ack", "tcp_rst", "tcp_synack", "tcp_finack",
                 "tcp_pshack", "packet_report", "attack_tracking_type")
POLICY_ORDER = ("policy_name", "state", "action", "priority", "src_network", "dst_network", "direction",
                "packet_reporting_status", "connection_limit_profile", "bdos_profile", "syn_protection_profile",
                "dns_flood_profile", "https_flood_profile", "traffic_filters_profile", "signature_protection_profile",
                "ert_attackers_feed_profile", "geo_feed_profile", "out_of_state_profile")


def _ordered(values: Dict, order) -> Dict:
    return {k: values[k] for k in order if k in values}


def _rows(data: NormalizedData, sheet: str, dev: str) -> List[NRow]:
    return [r for r in data.sheets.get(sheet, []) if r.device == dev and r.ok]


def _params(row: NRow, spec: S.SheetSpec) -> Dict:
    return {f.key: row.values[f.key] for f in spec.fields if f.in_params and f.key in row.values}


def build_device_config(dev: str, ip: str, data: NormalizedData) -> Dict:
    rc = data.run_control
    on = {t: rc.get(t) is True for t in S.RUN_CONTROL_TOGGLES}
    cfg: Dict = {"dp_ip": [ip]}

    # network classes: classes in order of first appearance, groups by Group Index
    netclasses: List[Dict] = []
    if on["create_network_classes"]:
        classes: Dict[str, List[NRow]] = {}
        for r in _rows(data, "Network_Classes", dev):
            classes.setdefault(r.values["name"], []).append(r)
        for name, rows in classes.items():
            groups = sorted(rows, key=lambda r: r.values["group_index"])
            netclasses.append({"name": name,
                               "groups": [{"address": g.values["address"], "mask": g.values["mask"]} for g in groups]})
    cfg["netclasses"] = netclasses

    cl_protections, cl_profiles = [], []
    if on["create_cl_profiles"]:
        cl_protections = [_ordered(r.values, CL_ORDER) for r in _rows(data, "CL_Protections", dev)]
        profiles: Dict[str, List[str]] = {}
        for r in _rows(data, "CL_Profile_Members", dev):
            profiles.setdefault(r.values["name"], []).append(r.values["protection"])
        cl_profiles = [{"name": n, "protections": p} for n, p in profiles.items()]
    cfg["cl_protections"] = cl_protections
    cfg["cl_profiles"] = cl_profiles

    cfg["oos_profiles"] = ([{"name": r.values["name"], "params": _params(r, S.OOS_PROFILES)}
                            for r in _rows(data, "OOS_Profiles", dev)]
                           if on["create_out_of_state_profiles"] else [])
    cfg["bdos_profiles"] = ([{"name": r.values["name"], "params": _params(r, S.BDOS_PROFILES)}
                             for r in _rows(data, "BDoS_Profiles", dev)]
                            if on["create_bdos_profiles"] else [])

    # Not generated by the POC; written empty so stale values can never be picked up.
    cfg["create_dns_profiles"] = []
    cfg["create_ssl_objects"] = []
    cfg["create_https_profiles"] = []

    tf_profiles, tf_rules = [], []
    if on["create_traffic_filter_profiles"]:
        tf_profiles = [{"profile_name": r.values["profile_name"], "action": r.values["action"]}
                       for r in _rows(data, "TF_Profiles", dev)]
        for r in _rows(data, "TF_Rules", dev):
            v = dict(r.values)
            v.update(v.pop("tcp_flags", {}) or {})
            tf_rules.append(_ordered(v, TF_RULE_ORDER))
    cfg["create_tf_profiles"] = tf_profiles
    cfg["create_tf_protections"] = tf_rules

    spc = {t: on[t] for t in S.TOGGLES if t != "apply_policies_after_creation"}
    # Always false in the generated file: policies are applied only by the separate,
    # authorized Phase B run (playbooks/update_policies.yml).
    spc["apply_policies_after_creation"] = False
    cfg["security_policy_config"] = {t: spc[t] for t in S.TOGGLES}

    cfg["create_security_policies"] = ([_ordered(r.values, POLICY_ORDER) for r in _rows(data, "Policies", dev)]
                                       if on["create_security_policies"] else [])
    return {k: cfg[k] for k in S.YAML_SECTION_ORDER}


def build_configs(data: NormalizedData, ctx: ValidationContext) -> Dict[str, Dict]:
    return {dev: build_device_config(dev, ip, data) for dev, ip in ctx.included}


def expected_counts(cfg: Dict) -> Dict[str, int]:
    """Object counts the result gate expects each module to report."""
    spc = cfg.get("security_policy_config", {})
    return {
        "network_groups": sum(len(nc.get("groups", [])) for nc in cfg.get("netclasses", [])) if spc.get("create_network_classes") else 0,
        "cl_protections": len(cfg.get("cl_protections", [])) if spc.get("create_cl_profiles") else 0,
        "cl_profile_links": sum(len(p.get("protections", [])) for p in cfg.get("cl_profiles", [])) if spc.get("create_cl_profiles") else 0,
        "oos_profiles": len(cfg.get("oos_profiles", [])) if spc.get("create_out_of_state_profiles") else 0,
        "bdos_profiles": len(cfg.get("bdos_profiles", [])) if spc.get("create_bdos_profiles") else 0,
        "tf_profiles": len(cfg.get("create_tf_profiles", [])) if spc.get("create_traffic_filter_profiles") else 0,
        "tf_protections": len(cfg.get("create_tf_protections", [])) if spc.get("create_traffic_filter_profiles") else 0,
        "policies": len(cfg.get("create_security_policies", [])) if spc.get("create_security_policies") else 0,
    }
