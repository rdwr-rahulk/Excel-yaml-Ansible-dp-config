"""The `xl2yaml run` flow: input -> checks -> preflight -> Phase A -> gate -> read-back -> Phase B."""

from __future__ import annotations

import copy
import json
from dataclasses import dataclass
from pathlib import Path
from typing import Optional

from . import logutil
from . import schema as S
from .convert import convert_workbook, load_yaml_input
from .gate import gate_phase_a, gate_phase_b, load_benign
from .input_select import EXCEL, InputError, select_input
from .manifest import Manifest, command_line, new_run_id
from .paths import Repo
from .preflight import Authorization, Target, load_allowlist, run_preflight
from .readback import compare_network_classes, get_vars_text
from .report import Report
from .runner import RunnerError, run_playbook
from .staging import StagingError, cleanup, collect_logs, stage
from .validator import Options
from .yamlio import dump, sha256_text


@dataclass
class RunArgs:
    env: Optional[str] = None
    device: Optional[str] = None
    input_mode: str = "auto"
    workbook: Optional[str] = None
    phase: str = "A"                 # A | B | AB
    after_run: Optional[str] = None  # Phase B only: run id of the passed Phase A
    preview: bool = False            # Phase A with --check (not safety evidence)
    confirm_targets: Optional[str] = None
    allow_ipv6: bool = False
    yaml_report_only: bool = False
    keep_staging: bool = False
    # YAML-mode authorization (Excel mode reads Run_Control)
    authorize_apply: bool = False
    change_ticket: Optional[str] = None
    authorized_by: Optional[str] = None


def update_vars_text(ip: str) -> str:
    return dump({"target_devices": [ip],
                 "update_settings": {"require_confirmation": False, "continue_on_error": False}},
                ["Generated by xl2yaml for Phase B (apply policies) - one device, stop on error."])


def run(args: RunArgs, repo: Optional[Repo] = None) -> int:
    repo = repo or Repo.find()
    run_id = new_run_id()
    run_dir = repo.runs_dir / run_id
    log = logutil.setup(run_dir / "xl2yaml.log")
    m = Manifest(run_id=run_id, command=command_line())
    log.info(f"xl2yaml run {run_id}  phase={args.phase}")

    def finish(code: int, result: str, report: Optional[Report] = None) -> int:
        m.result = result
        if report is not None:
            (run_dir / "report.txt").write_text(report.render(), encoding="utf-8")
            m.validation.setdefault("findings", [f.as_dict() for f in report.findings])
        path = m.save(repo.runs_dir)
        log.info(f"RESULT: {result}   manifest: {path}")
        return code

    # ---------------- input ----------------
    try:
        sel = select_input(repo, args.input_mode, args.workbook)
    except InputError as exc:
        log.error(f"[INPUT] {exc}")
        m.input = {"error": str(exc)}
        return finish(2, "FAILED_INPUT")
    m.input = sel.as_dict()

    report = Report()
    if sel.mode == EXCEL:
        res = convert_workbook(str(sel.source), sel.sha256, Options(allow_ipv6=args.allow_ipv6,
                               devices=[args.device] if args.device else None))
        report.extend(res.report)
        log.info(res.report.render(["VALIDATION (Excel mode)"]))
        if not res.ok:
            return finish(3, "FAILED_VALIDATION", report)
        if len(res.outputs) != 1:
            log.error("exactly one device per run: pass --device <name> (devices: "
                      + ", ".join(sorted(res.outputs)) + ")")
            return finish(3, "FAILED_TARGET", report)
        out = next(iter(res.outputs.values()))
        target, cfg, text = Target(out.name, out.ip), out.config, out.text
        rc = res.run_control
        env_wb = rc.get("environment")
        if args.env and env_wb and args.env != env_wb:
            log.error(f"--env {args.env} does not match Run_Control environment {env_wb}")
            return finish(3, "FAILED_TARGET", report)
        env = args.env or env_wb
        auth = Authorization(bool(rc.get(S.AUTHORIZE_APPLY)), rc.get("change_ticket"), rc.get("authorized_by"))
    else:
        rep, cfg0 = load_yaml_input(str(sel.source), allow_ipv6=args.allow_ipv6, report_only=args.yaml_report_only)
        report.extend(rep)
        log.info(rep.render(["VALIDATION (YAML mode)"]))
        if not rep.ok or cfg0 is None:
            return finish(3, "FAILED_VALIDATION", report)
        env = args.env
        if not env or not args.device:
            log.error("YAML mode needs --env and --device <name> (the IP is taken from the allowlist)")
            return finish(3, "FAILED_TARGET", report)
        al = repo.allowlist(env)
        if not al.is_file():
            log.error(f"{al} not found")
            return finish(3, "FAILED_TARGET", report)
        ips = [ip for ip, n in load_allowlist(al)["devices"].items() if n == args.device]
        if len(ips) != 1 or ips[0] not in (cfg0.get("dp_ip") or []):
            log.error(f"device {args.device} is not both on the {env} allowlist and in dp_ip of {sel.source}")
            return finish(3, "FAILED_TARGET", report)
        target = Target(args.device, ips[0])
        cfg = copy.deepcopy(cfg0)
        if cfg.get("dp_ip") != [target.ip]:
            m.notes.append(f"dp_ip narrowed from {cfg0.get('dp_ip')} to [{target.ip}] in the staged copy")
            log.info(f"[INPUT] dp_ip narrowed to [{target.ip}] in the staged copy (file on disk unchanged)")
        cfg["dp_ip"] = [target.ip]
        text = dump(cfg, [f"Staged from {sel.source.name} sha256={sel.sha256} (YAML mode)",
                          f"dp_ip limited to {target.name} ({target.ip})"])
        auth = Authorization(args.authorize_apply, args.change_ticket, args.authorized_by)

    m.environment = env
    m.devices = [{"name": target.name, "ip": target.ip}]
    m.toggles = dict(cfg.get("security_policy_config", {}))
    m.authorization = {"authorize_apply": auth.authorize_apply, "change_ticket": auth.change_ticket,
                       "authorized_by": auth.authorized_by}
    sha = sha256_text(text)
    # Data hash (ignores comments/header) links Phase B to the Phase A that created this configuration.
    cfg_sha = sha256_text(json.dumps(cfg, sort_keys=True))
    m.generated = [{"device": target.name, "sha256": sha, "config_sha256": cfg_sha}]
    (run_dir / f"create_vars_{target.name}.yml").write_bytes(text.encode("utf-8"))
    benign = load_benign(repo.benign_warnings)
    sections = [s for s, t in S.SECTION_TOGGLE.items() if cfg["security_policy_config"].get(t)]

    phase_a_passed: Optional[bool] = None
    # ---------------- Phase A ----------------
    if args.phase in ("A", "AB"):
        ok = _phase(repo, run_id, run_dir, "A", target, env, {"create_vars.yml": text}, "create_vars.yml", sha,
                    report, auth, m, args, sections=sections, playbook="create_full_config.yml",
                    gate=lambda r: gate_phase_a(r, cfg, benign, report, target.name))
        if ok is None:
            return finish(4, "FAILED_PREFLIGHT_A", report)
        if args.preview:
            return finish(0 if ok else 5, "PREVIEW_ONLY" if ok else "FAILED_PREVIEW", report)
        if not ok:
            return finish(5, "FAILED_PHASE_A", report)
        rb = _readback(repo, run_id, run_dir, target, cfg, report, m, args)
        if not rb:
            return finish(6, "FAILED_READBACK", report)
        phase_a_passed = True
        m.save(repo.runs_dir)

    # ---------------- Phase B ----------------
    if args.phase in ("B", "AB"):
        if args.phase == "B":
            phase_a_passed = _phase_a_record_ok(repo, args.after_run, target, cfg_sha, log)
        ut = update_vars_text(target.ip)
        ok = _phase(repo, run_id, run_dir, "B", target, env, {"update_vars.yml": ut}, "update_vars.yml",
                    sha256_text(ut), report, auth, m, args, phase_a_passed=phase_a_passed,
                    playbook="update_policies.yml", gate=lambda r: gate_phase_b(r, target.ip, benign, report, target.name))
        if ok is None:
            return finish(4, "FAILED_PREFLIGHT_B", report)
        if not ok:
            return finish(7, "FAILED_PHASE_B", report)
    return finish(0, "PASS", report)


def _phase(repo, run_id, run_dir, phase, target, env, files, vars_file, sha, report, auth, m, args,
           playbook, gate, phase_a_passed=None, sections=None):
    """Returns None if preflight failed, else the gate result."""
    log = logutil.get()
    try:
        staged = stage(repo, run_id, target.name, phase, files)
    except StagingError as exc:
        report.error("STAGING", str(exc), device=target.name, safety=True)
        return None
    try:
        pf = run_preflight(repo, env, target, phase, staged, vars_file, sha, report, auth,
                           phase_a_passed=phase_a_passed, confirm_targets=args.confirm_targets, sections=sections)
        m.preflight[phase] = {"result": "PASS" if pf.passed else "FAIL", "checks": pf.checks}
        if not pf.passed:
            return None
        try:
            r = run_playbook(staged, playbook, run_dir, check=(args.preview and phase == "A"))
        except RunnerError as exc:
            report.error("RUNNER", str(exc), device=target.name, safety=True)
            return False
        collect_logs(staged, run_dir)
        if r.check_mode:
            log.info("PREVIEW (--check): modules reported planned operations only; this is not safety evidence")
            m.phases[phase] = {"result": "PREVIEW", "returncode": r.returncode}
            return r.returncode == 0
        passed = gate(r)
        m.phases[phase] = {"result": "PASS" if passed else "FAIL", "returncode": r.returncode,
                           "playbook": playbook, "config_sha256": m.generated[0]["config_sha256"]}
        log.info(f"PHASE {phase} GATE: {'PASS' if passed else 'FAIL'}")
        return passed
    finally:
        if not args.keep_staging:
            cleanup(staged)


def _readback(repo, run_id, run_dir, target, cfg, report, m, args) -> bool:
    log = logutil.get()
    names = [nc["name"] for nc in cfg.get("netclasses") or []]
    if not names:
        m.readback = {"result": "SKIPPED", "detail": "no network classes created"}
        return True
    staged = stage(repo, run_id, target.name, "R", {"get_vars.yml": get_vars_text(target.ip, names)})
    try:
        r = run_playbook(staged, "get_network_class.yml", run_dir)
        ok = compare_network_classes(r, cfg, report, target.name)
    except RunnerError as exc:
        report.error("RUNNER", str(exc), device=target.name, safety=True)
        ok = False
    finally:
        if not args.keep_staging:
            cleanup(staged)
    m.readback = {"result": "PASS" if ok else "FAIL", "network_classes": names}
    log.info(f"READ-BACK: {'PASS' if ok else 'FAIL'}")
    return ok


def _phase_a_record_ok(repo: Repo, after_run: Optional[str], target: Target, sha: str, log) -> bool:
    if not after_run:
        log.error("Phase B alone needs --after-run <run id of the passed Phase A>")
        return False
    p = repo.runs_dir / after_run / "run_manifest.json"
    if not p.is_file():
        log.error(f"no manifest for run {after_run}")
        return False
    prev = Manifest.load(p)
    a = prev.phases.get("A", {})
    same = (a.get("result") == "PASS" and prev.readback.get("result") in ("PASS", "SKIPPED")
            and prev.devices == [{"name": target.name, "ip": target.ip}]
            and a.get("config_sha256") == sha)
    if not same:
        log.error(f"run {after_run} is not a passed Phase A for {target.name} with the same configuration")
    return same
