"""Workbook -> per-device YAML, and YAML-mode loading, with one shared report."""

from __future__ import annotations

from dataclasses import dataclass, field
from pathlib import Path
from typing import Dict, List, Optional, Tuple

from . import __version__
from . import schema as S
from .mapper import build_configs
from .normalize import NormalizedData, normalize
from .reader import read_workbook
from .report import Report
from .validator import Options, ValidationContext, validate
from .yaml_check import check_config
from .yamlio import dump, load, sha256_text


@dataclass
class DeviceOutput:
    name: str
    ip: str
    config: dict
    text: str
    sha256: str
    path: Optional[Path] = None


@dataclass
class ConvertResult:
    report: Report
    outputs: Dict[str, DeviceOutput] = field(default_factory=dict)
    data: Optional[NormalizedData] = None
    ctx: Optional[ValidationContext] = None

    @property
    def ok(self) -> bool:
        return self.report.ok

    @property
    def run_control(self) -> dict:
        return dict(self.data.run_control) if self.data else {}


def _header(source: str, source_sha: str, name: str, ip: str) -> List[str]:
    return [
        f"GENERATED by xl2yaml {__version__} from {source} - DO NOT EDIT BY HAND",
        f"source sha256: {source_sha}   template: v{S.TEMPLATE_VERSION}",
        f"device: {name} ({ip})",
        "apply_policies_after_creation is always false here: policies are applied only by the",
        "separate, authorized Phase B run (playbooks/update_policies.yml).",
    ]


def convert_workbook(path: str, source_sha: str, options: Optional[Options] = None,
                     source_label: Optional[str] = None) -> ConvertResult:
    report = Report()
    wb = read_workbook(path, report)
    result = ConvertResult(report)
    if wb is None:
        return result
    data = normalize(wb, report)
    ctx = validate(data, report, options)
    result.data, result.ctx = data, ctx
    if not report.ok:
        return result
    for name, cfg in build_configs(data, ctx).items():
        ip = cfg["dp_ip"][0]
        text = dump(cfg, _header(source_label or Path(path).name, source_sha, name, ip))
        # The generated file must pass the same checks as a hand-written one.
        check_config(cfg, report, source=f"generated:{name}", for_run=True,
                     allow_ipv6=bool(options and options.allow_ipv6))
        result.outputs[name] = DeviceOutput(name, ip, cfg, text, sha256_text(text))
    return result


def write_outputs(result: ConvertResult, out_dir: Path) -> List[DeviceOutput]:
    out_dir.mkdir(parents=True, exist_ok=True)
    written = []
    for name, o in sorted(result.outputs.items()):
        p = out_dir / f"create_vars_{name}.yml"
        p.write_bytes(o.text.encode("utf-8"))   # keep LF endings so the file hash equals o.sha256
        o.path = p
        written.append(o)
    return written


def load_yaml_input(path: str, allow_ipv6: bool = False, report_only: bool = False) -> Tuple[Report, Optional[dict]]:
    report = Report()
    try:
        cfg = load(path)
    except Exception as exc:  # noqa: BLE001
        report.error("YAML_UNREADABLE", f"cannot parse YAML: {exc}", sheet=path, safety=True)
        return report, None
    check_config(cfg, report, source=Path(path).name, for_run=True, allow_ipv6=allow_ipv6)
    if report_only:
        report.downgrade_non_safety_errors()
    return report, cfg
