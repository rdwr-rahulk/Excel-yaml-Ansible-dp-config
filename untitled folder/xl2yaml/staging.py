"""Isolated per-device, per-phase staging directories.

create_full_config.yml loads ``../vars/create_vars.yml`` directly. Passing a
generated file with ``-e`` would still let any key missing from it be filled
from an old file, so each run gets a fresh directory whose vars/ contains only
the files written for that run (whole-file replacement, never merged).
"""

from __future__ import annotations

import os
import shutil
import stat
from dataclasses import dataclass, field
from pathlib import Path
from typing import Dict

from .paths import Repo
from .yamlio import sha256_file

PLUGIN_DIR = Path(__file__).resolve().parent / "ansible_plugins"

ANSIBLE_CFG = """\
# Generated by xl2yaml for an isolated run. Do not edit.
[defaults]
inventory = ./inventory.ini
library = ./plugins/modules
module_utils = ./plugins/module_utils
host_key_checking = False
retry_files_enabled = False
callback_plugins = {callback_dir}
callbacks_enabled = xl2yaml_recorder
"""


class StagingError(Exception):
    pass


@dataclass
class StagedRun:
    dir: Path
    files: Dict[str, str] = field(default_factory=dict)   # vars file name -> sha256

    @property
    def ansible_cfg(self) -> Path:
        return self.dir / "ansible.cfg"

    def vars_path(self, name: str) -> Path:
        return self.dir / "vars" / name


def _ignore(_dir, names):
    return [n for n in names if n in ("__pycache__", "log", "tmp", ".DS_Store") or n.endswith(".pyc")]


DUMMY_CC = 'cc:\n  cc_ip: "192.0.2.1"\n  username: "syntax-check"\n  password: "syntax-check"\n  verify_ssl: false\n'
DUMMY_INVENTORY = "[CyberController]\ncc ansible_host=127.0.0.1 ansible_connection=local\n"


def stage(repo: Repo, run_id: str, device: str, phase: str, vars_files: Dict[str, str], dummy: bool = False) -> StagedRun:
    """Create the staging directory. ``dummy=True`` uses placeholder cc/inventory files (syntax checks in CI only)."""
    if not dummy:
        for required in (repo.inventory, repo.cc_vars):
            if not required.is_file():
                raise StagingError(f"{required} is missing (copy it from the *_example file and fill it in)")
    d = repo.staging_root / f"{run_id}_{device}_{phase}"
    if d.exists():
        raise StagingError(f"staging directory already exists: {d}")
    d.mkdir(parents=True, mode=0o700)
    os.chmod(d, 0o700)
    shutil.copytree(repo.playbooks, d / "playbooks", ignore=_ignore)
    shutil.copytree(repo.plugins, d / "plugins", ignore=_ignore)
    (d / "ansible.cfg").write_text(ANSIBLE_CFG.format(callback_dir=PLUGIN_DIR), encoding="utf-8")
    (d / "vars").mkdir(mode=0o700)
    if dummy:
        (d / "inventory.ini").write_text(DUMMY_INVENTORY, encoding="utf-8")
        (d / "vars" / "cc.yml").write_text(DUMMY_CC, encoding="utf-8")
    else:
        shutil.copy2(repo.inventory, d / "inventory.ini")
        shutil.copy2(repo.cc_vars, d / "vars" / "cc.yml")
    run = StagedRun(d)
    for name, text in vars_files.items():
        p = d / "vars" / name
        p.write_bytes(text.encode("utf-8"))   # bytes: no CRLF translation on Windows, so the hash matches the reviewed text
        os.chmod(p, stat.S_IRUSR | stat.S_IWUSR)
        run.files[name] = sha256_file(str(p))
    os.chmod(d / "vars" / "cc.yml", stat.S_IRUSR | stat.S_IWUSR)
    # code is read-only inside the staging copy
    for sub in ("playbooks", "plugins"):
        for p in (d / sub).rglob("*"):
            if p.is_file():
                os.chmod(p, stat.S_IRUSR)
    return run


def collect_logs(run: StagedRun, dest: Path) -> None:
    dest.mkdir(parents=True, exist_ok=True)
    for p in run.dir.rglob("log_*.log"):
        shutil.copy2(p, dest / f"module_{p.parent.parent.name}_{p.name}")


def cleanup(run: StagedRun) -> None:
    """Remove the staging copy, including vars/cc.yml and cached CC session cookies."""
    def _onerror(func, path, _exc):
        os.chmod(path, stat.S_IWUSR | stat.S_IRUSR | stat.S_IXUSR)
        func(path)
    if run.dir.exists():
        shutil.rmtree(run.dir, onerror=_onerror)
